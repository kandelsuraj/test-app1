/** @param {string} text */
function utf8(text) {
  /** @type {number[]} */
  const bytes = [];
  for (let i = 0; i < text.length; i += 1) {
    let code = text.charCodeAt(i);
    if (code >= 0xd800 && code < 0xdc00 && i + 1 < text.length) {
      const low = text.charCodeAt(i + 1);
      if (low >= 0xdc00 && low < 0xe000) {
        code = 0x10000 + ((code - 0xd800) << 10) + (low - 0xdc00);
        i += 1;
      }
    }
    // An unpaired surrogate encodes as U+FFFD, as Node's Buffer does.
    if (code >= 0xd800 && code < 0xe000) code = 0xfffd;
    if (code < 0x80) bytes.push(code);
    else if (code < 0x800) bytes.push(0xc0 | (code >> 6), 0x80 | (code & 63));
    else if (code < 0x10000) {
      bytes.push(0xe0 | (code >> 12), 0x80 | ((code >> 6) & 63), 0x80 | (code & 63));
    } else {
      bytes.push(
        0xf0 | (code >> 18),
        0x80 | ((code >> 12) & 63),
        0x80 | ((code >> 6) & 63),
        0x80 | (code & 63),
      );
    }
  }
  return bytes;
}

const HEX = "0123456789abcdef";

/**
 * Returns `(message) => hex tag` for the key whose first block the server has
 * already compressed. `keyState` is that state as 64 hex characters.
 * Returns null when the state is malformed.
 * @param {string} keyState
 */
export function blake2sMac(keyState) {
  if (!/^[0-9a-f]{64}$/.test(keyState)) return null;

  /** @type {number[]} */
  const initial = [];
  for (let i = 0; i < 8; i += 1) {
    // Little-endian words, matching the server's encoding.
    let word = 0;
    for (let byte = 3; byte >= 0; byte -= 1) {
      word = (word << 8) | parseInt(keyState.substr(i * 8 + byte * 2, 2), 16);
    }
    initial.push(word | 0);
  }

  /** @param {string} message */
  return (message) => {
    const bytes = utf8(message);
    const h = initial.slice();
    // The key block already counted 64 bytes.
    let counter = 64;
    let offset = 0;

    do {
      const remaining = bytes.length - offset;
      const last = remaining <= 64;
      const block = bytes.slice(offset, offset + 64);
      while (block.length < 64) block.push(0);
      counter += last ? remaining : 64;
      compress(h, block, counter, last);
      offset += 64;
    } while (offset < bytes.length);

    let hex = "";
    for (let i = 0; i < 8; i += 1) {
      const word = h[i];
      for (let byte = 0; byte < 4; byte += 1) {
        const value = (word >>> (byte * 8)) & 255;
        hex += HEX[value >> 4] + HEX[value & 15];
      }
    }
    return hex;
  };
}

/**
 * Compares without bailing at the first difference.
 * @param {string} a
 * @param {string} b
 */
export function safeEqual(a, b) {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i += 1) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}
